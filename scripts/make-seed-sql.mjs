// Generates supabase/seed.sql from src/data/mockRecipes.ts.
// Usage: node scripts/make-seed-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

const src = readFileSync("src/data/mockRecipes.ts", "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { mockRecipes } = await import("data:text/javascript;base64," + Buffer.from(js).toString("base64"));

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const rows = mockRecipes.map(
  (r) =>
    `  (${[
      q(r.title), q(r.author), q(r.category), r.prepTime, r.cookTime, r.servings,
      q(r.images[0]), `${q(JSON.stringify(r.images))}::jsonb`, q(r.description), `${q(JSON.stringify(r.ingredients))}::jsonb`,
      `${q(JSON.stringify(r.steps))}::jsonb`, q(r.chefsNotes), "null", q(r.createdAt),
    ].join(", ")})`,
);

const sql = `-- Sample recipes for the shared book. Run once in the Supabase SQL editor,
-- after schema.sql (and add-images.sql on an older project). Generated by scripts/make-seed-sql.mjs; owner_id is null,
-- so nobody can edit or delete these.

alter table public.recipes alter column owner_id drop not null;

insert into public.recipes
  (title, author, category, prep_time, cook_time, servings, image_url, images, description,
   ingredients, steps, chefs_notes, owner_id, created_at)
values
${rows.join(",\n")};
`;
writeFileSync("supabase/seed.sql", sql);
console.log(`wrote supabase/seed.sql (${mockRecipes.length} recipes)`);
